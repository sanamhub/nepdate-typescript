// Writes the generated tables from shared/data (ADR-0001 §8) and checks every data-derived count
// against the hub's shared/spec/vectors/patro-summary.json (ADR-0017). Run from the repository root:
//   node scripts/codegen.ts           write the files
//   node scripts/codegen.ts --check   exit 1 if a file on disk differs from what would be written

import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const HEADER = "// Generated by scripts/codegen.ts. DO NOT EDIT.\n";
const MIN_YEAR = 1901;
const MAX_YEAR = 2199;
const YEARS = MAX_YEAR - MIN_YEAR + 1;
const MONTHS = YEARS * 12;
const MAX_SERIAL = 109211;

interface CalendarJson {
  min_year: number;
  max_year: number;
  month_lengths: Record<string, number[]>;
}

interface Named {
  np: string;
  en: string;
}

interface DayJson {
  tithi?: Named;
  holiday?: boolean;
  events?: Named[];
}

interface PatroJson {
  schema: number;
  year: number;
  days: Record<string, DayJson>;
}

/** The hub's counts for the vendored patro data (shared/spec/vectors/patro-summary.json). */
interface PatroSummary {
  schema: number;
  first_year: number;
  last_year: number;
  first_day: string;
  last_day: string;
  first_serial: number;
  last_serial: number;
  days: number;
  tithi_first_day: string;
  tithi_last_day: string;
  tithi_first_serial: number;
  tithi_days: number;
  tithi_names: number;
  holidays: number;
  event_days: number;
  events: number;
  event_names: number;
  names: number;
  name_bytes: number;
}

function fail(message: string): never {
  console.error(`codegen: ${message}`);
  process.exit(1);
}

function readCalendar(): number[][] {
  const json = JSON.parse(
    readFileSync("shared/data/calendar/bs-calendar.json", "utf8"),
  ) as CalendarJson;
  if (json.min_year !== MIN_YEAR || json.max_year !== MAX_YEAR) {
    fail(`expected years ${MIN_YEAR}..${MAX_YEAR}, got ${json.min_year}..${json.max_year}`);
  }
  const years: number[][] = [];
  for (let y = MIN_YEAR; y <= MAX_YEAR; y++) {
    const lengths = json.month_lengths[String(y)];
    if (lengths === undefined || lengths.length !== 12) {
      fail(`year ${y} must have 12 month lengths`);
    }
    for (const len of lengths) {
      if (!Number.isInteger(len) || len < 29 || len > 32) {
        fail(`year ${y} has month length ${len}, expected 29..32`);
      }
    }
    years.push(lengths);
  }
  if (Object.keys(json.month_lengths).length !== MAX_YEAR - MIN_YEAR + 1) {
    fail("month_lengths has years outside the range");
  }
  return years;
}

/** Serial of the first day of every month, `MONTH_START[monthIndex]` (ALGORITHM §4). */
function monthStarts(years: number[][]): Int32Array {
  const starts = new Int32Array(MONTHS + 1);
  let serial = 0;
  for (let y = 0; y < YEARS; y++) {
    const lengths = years[y] as number[];
    for (let m = 0; m < 12; m++) {
      starts[y * 12 + m] = serial;
      serial += lengths[m] as number;
    }
  }
  starts[MONTHS] = serial;
  return starts;
}

// days_from_civil(1844, 4, 11), ALGORITHM §2. Date.UTC is fine here: the generator is not the core.
const EPOCH_UNIX_DAYS = Date.UTC(1844, 3, 11) / 86_400_000;

// ADR-0002 §5: 2 bits per month (length - 29), month k of the whole range in byte k >> 2 at bit
// 2 * (k & 3), so month 1 of 1901 sits in the low bits of byte 0.
function packMonthLengths(years: number[][]): string {
  const lengths = years.flat();
  const bytes = new Uint8Array(Math.ceil(lengths.length / 4));
  lengths.forEach((len, k) => {
    bytes[k >> 2] = (bytes[k >> 2] as number) | ((len - 29) << (2 * (k & 3)));
  });
  return Buffer.from(bytes).toString("base64");
}

function calendarSource(years: number[][]): string {
  return `${HEADER}
/** The first BS year in the tables. */
export const MIN_YEAR = ${MIN_YEAR};
/** The last BS year in the tables. */
export const MAX_YEAR = ${MAX_YEAR};
/** Days from 1970-01-01 to BS 1901-01-01 (AD 1844-04-11). */
export const EPOCH_UNIX_DAYS = ${EPOCH_UNIX_DAYS};

/** The ${years.length * 12} month lengths from MIN_YEAR, 2 bits each (length - 29), base64. */
export const PACKED_MONTH_LENGTHS =
  "${packMonthLengths(years)}";
`;
}

function base64(bytes: Uint8Array): string {
  return Buffer.from(bytes).toString("base64");
}

function encodeInt32(values: readonly number[]): string {
  const bytes = new Uint8Array(values.length * 4);
  const view = new DataView(bytes.buffer);
  for (let i = 0; i < values.length; i++) view.setInt32(i * 4, values[i] as number, true);
  return base64(bytes);
}

function encodeUint16(values: readonly number[]): string {
  const bytes = new Uint8Array(values.length * 2);
  const view = new DataView(bytes.buffer);
  for (let i = 0; i < values.length; i++) view.setUint16(i * 2, values[i] as number, true);
  return base64(bytes);
}

function nameKey(named: Named): string {
  return `${named.np}\u0000${named.en}`;
}

function readNamed(value: unknown, where: string): Named {
  if (typeof value !== "object" || value === null) fail(`${where}: expected {np, en}`);
  const { np, en } = value as Partial<Named>;
  if (typeof np !== "string" || np === "" || typeof en !== "string" || en === "") {
    fail(`${where}: np and en must be non-empty strings`);
  }
  return { np, en };
}

interface Patro {
  coverageFirst: number;
  coverageLast: number;
  coverageFirstDay: string;
  coverageLastDay: string;
  tithiFirst: number;
  tithiFirstDay: string;
  tithiLastDay: string;
  tithiIds: Uint8Array;
  holidayDays: number[];
  eventDays: number[];
  eventCounts: number[];
  eventNameIds: number[];
  namesNp: string[];
  namesEn: string[];
}

/**
 * Reads every `shared/data/patro/<year>.json` into the layout of PATRO §3: a contiguous tithi id
 * per day, sorted holiday and event-day serials, events per day, and one deduplicated name pool.
 * The tithi pairs come first in the pool, so the per-day tithi id fits in a byte.
 */
function readPatro(starts: Int32Array): Patro {
  const dir = "shared/data/patro";
  const files = readdirSync(dir)
    .filter((file) => /^\d{4}\.json$/.test(file))
    .sort();
  if (files.length === 0) fail(`${dir} has no year files`);

  interface Entry {
    serial: number;
    label: string;
    day: DayJson;
  }
  const entries: Entry[] = [];
  const seen = new Set<number>();
  for (const file of files) {
    const json = JSON.parse(readFileSync(`${dir}/${file}`, "utf8")) as PatroJson;
    if (json.schema !== 1) fail(`${file}: schema ${json.schema}, expected 1`);
    const fileYear = Number(file.slice(0, 4));
    if (json.year !== fileYear) fail(`${file}: year ${json.year} does not match the file name`);
    for (const [label, day] of Object.entries(json.days)) {
      const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(label);
      if (match === null) fail(`${file}: date ${label} is not YYYY-MM-DD`);
      const year = Number(match[1]);
      const month = Number(match[2]);
      const dayOfMonth = Number(match[3]);
      if (year !== fileYear) fail(`${file}: date ${label} is not in ${fileYear}`);
      if (month < 1 || month > 12) fail(`${file}: date ${label} has month ${month}`);
      const monthIndex = (year - MIN_YEAR) * 12 + month - 1;
      const start = starts[monthIndex] as number;
      const length = (starts[monthIndex + 1] as number) - start;
      if (dayOfMonth < 1 || dayOfMonth > length) {
        fail(`${file}: date ${label} has day ${dayOfMonth}, month ${year}-${month} has ${length}`);
      }
      const serial = start + dayOfMonth - 1;
      if (seen.has(serial)) fail(`${file}: duplicate day ${label}`);
      seen.add(serial);
      entries.push({ serial, label, day });
    }
  }
  entries.sort((a, b) => a.serial - b.serial);

  const poolIndex = new Map<string, number>();
  const namesNp: string[] = [];
  const namesEn: string[] = [];
  const poolId = (named: Named): number => {
    const key = nameKey(named);
    let id = poolIndex.get(key);
    if (id === undefined) {
      id = namesNp.length;
      poolIndex.set(key, id);
      namesNp.push(named.np);
      namesEn.push(named.en);
    }
    return id;
  };

  const tithiDays: { serial: number; label: string; named: Named }[] = [];
  const holidayDays: number[] = [];
  const eventsByDay = new Map<number, Named[]>();
  let coverageFirst = Number.POSITIVE_INFINITY;
  let coverageLast = Number.NEGATIVE_INFINITY;
  let coverageFirstDay = "";
  let coverageLastDay = "";
  for (const { serial, label, day } of entries) {
    let hasData = false;
    if (day.tithi !== undefined) {
      const named = readNamed(day.tithi, `${label}.tithi`);
      tithiDays.push({ serial, label, named });
      poolId(named);
      hasData = true;
    }
    if (day.holiday !== undefined) {
      if (typeof day.holiday !== "boolean") fail(`${label}.holiday must be a boolean`);
      if (day.holiday) {
        holidayDays.push(serial);
        hasData = true;
      }
    }
    if (day.events !== undefined) {
      if (!Array.isArray(day.events)) fail(`${label}.events must be an array`);
      if (day.events.length > 0) {
        eventsByDay.set(
          serial,
          day.events.map((event, i) => readNamed(event, `${label}.events[${i}]`)),
        );
        hasData = true;
      }
    }
    if (serial > MAX_SERIAL) fail(`${label}: serial ${serial} is past MAX_SERIAL`);
    if (hasData) {
      if (serial < coverageFirst) {
        coverageFirst = serial;
        coverageFirstDay = label;
      }
      if (serial > coverageLast) {
        coverageLast = serial;
        coverageLastDay = label;
      }
    }
  }
  if (tithiDays.length === 0) fail("no tithi data");
  if (holidayDays.length === 0) fail("no holidays");
  if (eventsByDay.size === 0) fail("no events");

  const tithiFirst = (tithiDays[0] as { serial: number }).serial;
  const tithiLast = (tithiDays[tithiDays.length - 1] as { serial: number }).serial;
  const tithiFirstDay = (tithiDays[0] as { label: string }).label;
  const tithiLastDay = (tithiDays[tithiDays.length - 1] as { label: string }).label;
  const gaps = new Int16Array(tithiLast - tithiFirst + 1).fill(-1);
  for (const { serial, named } of tithiDays) {
    const offset = serial - tithiFirst;
    if (gaps[offset] !== -1) fail(`tithi data repeats the day at serial ${serial}`);
    gaps[offset] = poolId(named);
  }
  for (let offset = 0; offset < gaps.length; offset++) {
    if (gaps[offset] === -1) fail(`tithi data has a gap at serial ${tithiFirst + offset}`);
  }
  const tithiIds = new Uint8Array(gaps.length);
  for (let offset = 0; offset < gaps.length; offset++) tithiIds[offset] = gaps[offset] as number;

  const eventDays = [...eventsByDay.keys()].sort((a, b) => a - b);
  const eventCounts: number[] = [];
  const eventNameIds: number[] = [];
  for (const serial of eventDays) {
    const events = eventsByDay.get(serial) as Named[];
    eventCounts.push(events.length);
    for (const event of events) eventNameIds.push(poolId(event));
  }

  if (namesNp.length > 65_535) fail("the name pool does not fit in Uint16");
  if (tithiIds.some((id) => id > 255)) fail("a tithi id does not fit in Uint8");
  return {
    coverageFirst,
    coverageLast,
    coverageFirstDay,
    coverageLastDay,
    tithiFirst,
    tithiFirstDay,
    tithiLastDay,
    tithiIds,
    holidayDays,
    eventDays,
    eventCounts,
    eventNameIds,
    namesNp,
    namesEn,
  };
}

function readSummary(): PatroSummary {
  const path = "shared/spec/vectors/patro-summary.json";
  let summary: PatroSummary;
  try {
    summary = JSON.parse(readFileSync(path, "utf8")) as PatroSummary;
  } catch {
    fail(`cannot read ${path}; run the hub sync to vendor the shared spec vectors`);
  }
  if (summary.schema !== 1) fail(`${path}: schema ${summary.schema}, expected 1`);
  return summary;
}

function checkCount(field: string, summary: number, data: number): void {
  if (summary !== data) fail(`patro-summary ${field} is ${summary}, the data has ${data}`);
}

function checkDay(field: string, summary: string, data: string): void {
  if (summary !== data) fail(`patro-summary ${field} is ${summary}, the data has ${data}`);
}

function nameBytes(patro: Patro): number {
  let total = 0;
  for (let i = 0; i < patro.namesNp.length; i++) {
    total += Buffer.byteLength(patro.namesNp[i] as string, "utf8");
    total += Buffer.byteLength(patro.namesEn[i] as string, "utf8");
  }
  return total;
}

/** Fails when the vendored data and the hub's counts disagree, naming the field and both values. */
function validateSummary(patro: Patro): void {
  const summary = readSummary();
  checkCount("first_year", summary.first_year, Number(patro.coverageFirstDay.slice(0, 4)));
  checkCount("last_year", summary.last_year, Number(patro.coverageLastDay.slice(0, 4)));
  checkDay("first_day", summary.first_day, patro.coverageFirstDay);
  checkDay("last_day", summary.last_day, patro.coverageLastDay);
  checkCount("first_serial", summary.first_serial, patro.coverageFirst);
  checkCount("last_serial", summary.last_serial, patro.coverageLast);
  checkCount("days", summary.days, patro.coverageLast - patro.coverageFirst + 1);
  checkDay("tithi_first_day", summary.tithi_first_day, patro.tithiFirstDay);
  checkDay("tithi_last_day", summary.tithi_last_day, patro.tithiLastDay);
  checkCount("tithi_first_serial", summary.tithi_first_serial, patro.tithiFirst);
  checkCount("tithi_days", summary.tithi_days, patro.tithiIds.length);
  checkCount("tithi_names", summary.tithi_names, new Set(patro.tithiIds).size);
  checkCount("holidays", summary.holidays, patro.holidayDays.length);
  checkCount("event_days", summary.event_days, patro.eventDays.length);
  checkCount("events", summary.events, patro.eventNameIds.length);
  checkCount("event_names", summary.event_names, new Set(patro.eventNameIds).size);
  checkCount("names", summary.names, patro.namesNp.length);
  checkCount("name_bytes", summary.name_bytes, nameBytes(patro));
}

function stringArray(name: string, values: readonly string[], comment: string): string {
  const body = values.map((value) => `  ${JSON.stringify(value)},\n`).join("");
  return `/** ${comment} */\nexport const ${name}: readonly string[] = [\n${body}];\n`;
}

function patroSource(patro: Patro): string {
  const tithiDays = patro.tithiIds.length;
  return `${HEADER}
// PATRO §3: base64 typed arrays decoded at load (ADR-0002 §7), plus the name pool. The tithi ids
// come first in the pool, so TITHI_IDS holds one byte per day.

/** Serial of BS 2077-01-01, the first day with any data. */
export const COVERAGE_FIRST = ${patro.coverageFirst};
/** Serial of BS 2084-08-20, the last day with any data. */
export const COVERAGE_LAST = ${patro.coverageLast};
/** Serial of the first tithi day, BS 2078-01-02. */
export const TITHI_FIRST = ${patro.tithiFirst};

/** ${tithiDays} tithi ids, one per day from TITHI_FIRST, base64 Uint8Array. */
export const TITHI_IDS =
  "${base64(patro.tithiIds)}";
/** ${patro.holidayDays.length} holiday serials in ascending order, base64 Int32Array. */
export const HOLIDAY_DAYS =
  "${encodeInt32(patro.holidayDays)}";
/** ${patro.eventDays.length} event-day serials in ascending order, base64 Int32Array. */
export const EVENT_DAYS =
  "${encodeInt32(patro.eventDays)}";
/** ${patro.eventCounts.length} event counts, one per entry of EVENT_DAYS, base64 Uint8Array. */
export const EVENT_COUNTS =
  "${base64(Uint8Array.from(patro.eventCounts))}";
/** ${patro.eventNameIds.length} name ids, in file order per day, base64 Uint16Array. */
export const EVENT_NAME_IDS =
  "${encodeUint16(patro.eventNameIds)}";

${stringArray("NAMES_NP", patro.namesNp, "The np side of the deduplicated name pool.")}
${stringArray("NAMES_EN", patro.namesEn, "The en side of the deduplicated name pool, same indices as NAMES_NP.")}`;
}

const years = readCalendar();
const patro = readPatro(monthStarts(years));
validateSummary(patro);
const outputs: [path: string, content: string][] = [
  ["packages/nepdate/src/calendar.gen.ts", calendarSource(years)],
  ["packages/nepdate-patro/src/tables.gen.ts", patroSource(patro)],
];

const check = process.argv.includes("--check");
let drift = false;
for (const [path, content] of outputs) {
  if (check) {
    let onDisk = "";
    try {
      onDisk = readFileSync(path, "utf8");
    } catch {
      // A missing file is drift too.
    }
    if (onDisk !== content) {
      console.error(`codegen: ${path} differs from the generator output; run npm run codegen`);
      drift = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`codegen: wrote ${path}`);
  }
}
if (drift) process.exit(1);
